package com.buukle.agent.common.config;

public final class SystemConfigKeys {

    public static final String AES_KEY = "crypto.aes-key";
    public static final String CHROME_EXTENSION_TOKEN = "chrome.extension-token";
    public static final String JINA_API_KEY = "web-read.jina-api-key";
    public static final String LOGIN_MAX_ATTEMPTS = "rate-limit.login-max-attempts";
    public static final String LOGIN_WINDOW_MINUTES = "rate-limit.login-window-minutes";
    public static final String SSO_BASE_URL = "sso.base-url";
    /** Download URL of the Chrome extension package (set to the hosted route when uploaded in-app, or filled in manually by an admin as an external link; empty hides the entry point in the UI) */
    public static final String PLUGIN_DOWNLOAD_URL = "plugin.download-url";
    /** Chrome Web Store listing URL for the extension; empty hides the store option in the UI */
    public static final String PLUGIN_STORE_URL = "plugin.store-url";
    /**
     * Minimum required Chrome extension version (e.g. {@code 1.0.118}); empty = no prompt.
     *
     * <p>The extension popup compares its local {@code getManifest().version} against it and shows an
     * upgrade prompt when lower. The release package version is generated by {@code deploy.yml} from
     * the tag ({@code v1.0.NNN-alpha} → {@code 1.0.NNN}); note this is unrelated to the literal
     * version in the repository's manifest.json.
     */
    public static final String PLUGIN_MIN_EXTENSION_VERSION = "plugin.min-extension-version";
    /** Default resource template (JSON array, used when initializing a new user; empty means no resources are initialized) */
    public static final String USER_RESOURCE_TEMPLATE = "user.resource-template";
    /** Default resources created together with a tenant (JSON array, tenant-owned resources) */
    public static final String TENANT_RESOURCE_TEMPLATE = "tenant.resource-template";
    /** Global LLM sampling defaults (JSON, same shape as instance/completions config; the global fallback for agent flows) */
    public static final String LLM_DEFAULTS_CONFIG = "llm.defaults-config";
    /** Kill switch for historical session cleanup ("true"/"false"): cleanup hard-deletes irreversibly, so turn this off first when something goes wrong — no redeploy needed */
    public static final String SESSION_CLEANUP_ENABLED = "session.cleanup-enabled";
    /** Session data retention days: sessions (and their related data) whose created_at and updated_at are both earlier than this are cleaned up */
    public static final String SESSION_CLEANUP_RETENTION_DAYS = "session.cleanup-retention-days";
    /** Retention days for screenshots and chat attachments (agent_file_store; a single screenshot is capped at 8MB and dominates disk usage, hence configured separately from text) */
    public static final String SESSION_FILE_RETENTION_DAYS = "session.file-retention-days";
    /** Retention days for the cleanup task's own run records (agent_session_cleanup_run): the record table itself must be pruned too, or it grows without bound */
    public static final String SESSION_CLEANUP_LOG_RETENTION_DAYS = "session.cleanup-log-retention-days";
    /** Kill switch for Skill Hub auto-sync ("true"/"false"): once off, only manual triggering remains */
    public static final String SKILL_AUTO_UPDATE_ENABLED = "skill.auto-update-enabled";
    /** Retention days for skill auto-sync run records (capability_skill_sync_run): one row per scan round, so it grows forever unless pruned */
    public static final String SKILL_SYNC_LOG_RETENTION_DAYS = "skill.sync-log-retention-days";
    /** Global Agent Router system prompt; blank falls back to the built-in template. */
    public static final String SUPER_AGENT_ROUTER_SYSTEM_PROMPT = "super-agent.router-system-prompt";

    /** Config keys that may be read publicly without authentication (safe/non-sensitive entries only) */
    public static final java.util.Set<String> PUBLIC_KEYS =
            java.util.Set.of(PLUGIN_DOWNLOAD_URL, PLUGIN_STORE_URL, PLUGIN_MIN_EXTENSION_VERSION);

    private SystemConfigKeys() {}
}
