package com.buukle.agent.instance.dtvo.vo;

import lombok.Data;

import java.io.Serializable;

@Data
public class SessionVO implements Serializable {
    private Long id;
    private String title;
    private Long agentInstanceId;
    /** Display name of the bound agent instance (session list tag). */
    private String agentInstanceName;
    private Long tenantId;
    private String status;
    private String runMode;
    /** CONSOLE / WIDGET / TASK / GROUP_ROUTER / ROUTER / WORKER / TRAINING / WATCHDOG。 */
    private String sessionType;
    private Long superAgentId;
    private Long threadId;
    private String summary;
    private String summaryUpdatedAt;
    private Long summaryModelRouteId;
    private Boolean titleAutoGenerated;
    private String createdAt;
    private String createdBy;
    private String updatedBy;
    private String updatedAt;
    /** True when the caller may only view this session (not send / stop / rename / delete). */
    private Boolean readOnly;
}
