@Service
@RequiredArgsConstructor
public class SessionServiceImpl extends ServiceImpl<SessionMapper, AgentSession> implements SessionService {
    private static final List<String> USER_SESSION_TYPES = List.of(
            SessionType.CONSOLE, SessionType.WIDGET, SessionType.TASK, SessionType.TRAINING);
    private static final String ROLE_USER = "USER";
    private static final String ROLE_ROUTER = "ROUTER";
    private static final String ROLE_WORKER = "WORKER";

    private final SessionConverter sessionConverter;
    private final ApplicationEventPublisher eventPublisher;
    private final InstanceMapper instanceMapper;

    @Override
    public SessionVO createSession(CreateSessionDTO dto) {
        AgentInstance instance = instanceMapper.selectById(dto.getAgentInstanceId());
        if (instance == null) {
            throw new BizException(InstanceErrorCode.INSTANCE_NOT_FOUND);
        }
        assertSurfaceAllowed(instance);
        if (instance.getModelRouteId() == null && dto.getOverrideModelRouteId() == null) {
            throw new BizException(InstanceErrorCode.INSTANCE_NO_MODEL_ROUTE);
        }
        AgentSession session = sessionConverter.toDO(dto);
        session.setTitleAutoGenerated(true);
        save(session);
        SessionVO vo = sessionConverter.toVO(session);
        vo.setAgentInstanceName(instance.getName());
        SessionCreatedEvent event = new SessionCreatedEvent();
        event.setSessionId(vo.getId());
        event.setAgentInstanceId(dto.getAgentInstanceId());
        eventPublisher.publishEvent(event);
        return vo;
    }

    @Override
    public SessionVO getSession(Long id) {
        AgentSession session = getById(id);
        if (session == null) throw new BizException(InstanceErrorCode.SESSION_NOT_FOUND);
        if (SessionStatus.STATUS_CLOSED.equals(session.getStatus()))
            throw new BizException(InstanceErrorCode.SESSION_CLOSED);
        SessionVO vo = sessionConverter.toVO(session);
        fillInstanceNames(List.of(vo));
        return vo;
    }

    @Override
    public SessionVO updateSession(Long id, String title) {
        AgentSession session = getById(id);
        if (session == null) throw new BizException(InstanceErrorCode.SESSION_NOT_FOUND);
        session.setTitle(title);
        session.setTitleAutoGenerated(false);
        updateById(session);
        return sessionConverter.toVO(session);
    }

    @Override
    public SessionVO updateRunMode(Long id, String runMode) {
        AgentSession session = getById(id);
        if (session == null) throw new BizException(InstanceErrorCode.SESSION_NOT_FOUND);
        session.setRunMode(com.buukle.agent.common.constant.RunMode.from(runMode).name());
        updateById(session);
        return sessionConverter.toVO(session);
    }

    @Override
    public SessionVO findActiveTrainingSession(Long superAgentId, String createdBy) {
        if (superAgentId == null || createdBy == null || createdBy.isBlank()) {
            return null;
        }
        AgentSession session = lambdaQuery()
                .eq(AgentSession::getSuperAgentId, superAgentId)
                .eq(AgentSession::getSessionType, SessionType.TRAINING)
                .eq(AgentSession::getCreatedBy, createdBy)
                .eq(AgentSession::getStatus, SessionStatus.STATUS_ACTIVE)
                .orderByDesc(AgentSession::getId)
                .last("LIMIT 1")
                .one();
        return session == null ? null : sessionConverter.toVO(session);
    }

    @Override
    public List<SessionVO> listSessions(int offset, int limit, String keyword) {
        return listSessions(offset, limit, keyword, SessionListScope.USER, ROLE_USER);
    }

    @Override
    public List<SessionVO> listSessions(int offset, int limit, String keyword, String scope, String role) {
        boolean tenantScope = SessionListScope.TENANT.equalsIgnoreCase(scope);
        boolean groupScope = SessionListScope.GROUP.equalsIgnoreCase(scope);
        String requestedRole = role == null || role.isBlank()
                ? ROLE_USER : role.trim().toUpperCase();
        List<String> sessionTypes = switch (requestedRole) {
            case ROLE_ROUTER -> List.of(SessionType.ROUTER);
            case ROLE_WORKER -> List.of(SessionType.WORKER);
            default -> USER_SESSION_TYPES;
        };
        boolean tenantAdmin = SessionAccessPolicy.isTenantAdmin();
        String username = AuthContext.getUsername();

        TenantScope previousScope = TenantScopeHolder.get();
        try {
            TenantScope currentScope = TenantScopeHolder.currentOrFallback();
            if (tenantAdmin && !groupScope && currentScope != null && currentScope.selfOnly()) {
                // Tenant administrators may read tenant sessions even when their assignment is SELF_ONLY.
                TenantScopeHolder.start(new TenantScope(
                        currentScope.userId(), currentScope.username(), currentScope.currentTenantId(),
                        currentScope.visibleTenantIds(), false,
                        currentScope.manageableTenantIds(), currentScope.subtreeVisible()));
            }
            var query = lambdaQuery()
                    .eq(AgentSession::getStatus, SessionStatus.STATUS_ACTIVE)
                    .isNull(AgentSession::getParentSessionId)
                    .like(keyword != null && !keyword.isBlank(), AgentSession::getTitle, keyword);
            if (tenantScope || groupScope) {
                query.eq(AgentSession::getSessionType, SessionType.GROUP_ROUTER);
                if (groupScope) {
                    query.eq(AgentSession::getCreatedBy, username);
                }
            } else {
                // Legacy rows may have a null session_type; they are console conversations.
                query.and(w -> w.in(AgentSession::getSessionType, sessionTypes)
                        .or().isNull(AgentSession::getSessionType));
                if (!tenantAdmin) {
                    // Tenant visibility level must not expose other users' conversations.
                    query.eq(AgentSession::getCreatedBy, username);
                }
            }
            List<SessionVO> result = query
                    .orderByDesc(AgentSession::getUpdatedAt)
                    .last("OFFSET " + offset + " LIMIT " + limit)
                    .list()
                    .stream()
                    .map(this::toAccessVO)
                    .toList();
            fillInstanceNames(result);
            return result;
        } finally {
            if (previousScope == null) {
                TenantScopeHolder.clear();
            } else {
                TenantScopeHolder.start(previousScope);
            }
        }
    }

    private SessionVO toAccessVO(AgentSession session) {
        SessionVO vo = sessionConverter.toVO(session);
        if (vo != null) {
            vo.setReadOnly(!SessionAccessPolicy.canWrite(
                    session.getTenantId(), session.getCreatedBy(), session.getSessionType()));
        }
        return vo;
    }

    /** Fills the instance display name used by the session list tag. */
    private void fillInstanceNames(Collection<SessionVO> sessions) {
        if (sessions == null || sessions.isEmpty()) {
            return;
        }
        List<Long> ids = sessions.stream()
                .map(SessionVO::getAgentInstanceId)
                .filter(Objects::nonNull)
                .distinct()
                .toList();
        if (ids.isEmpty()) {
            return;
        }
        Map<Long, String> names = lookupInstanceNames(ids);
        for (SessionVO session : sessions) {
            if (session.getAgentInstanceId() != null) {
                session.setAgentInstanceName(names.get(session.getAgentInstanceId()));
            }
        }
    }

    /**
     * Instance names are display-only. A visible session may reference a tenant-owned instance the
     * caller cannot open (for example the tenant Group Router), so the self-only filter is lifted
     * for this id-to-name lookup while the tenant boundary itself stays enforced.
     */
    private Map<Long, String> lookupInstanceNames(List<Long> ids) {
        TenantScope previous = TenantScopeHolder.get();
        TenantScope current = TenantScopeHolder.currentOrFallback();
        boolean widen = current != null && current.selfOnly();
        try {
            if (widen) {
                TenantScopeHolder.start(new TenantScope(
                        current.userId(), current.username(), current.currentTenantId(),
                        current.visibleTenantIds(), false,
                        current.manageableTenantIds(), current.subtreeVisible()));
            }
            return instanceMapper.selectBatchIds(ids).stream()
                    .collect(Collectors.toMap(AgentInstance::getId, AgentInstance::getName,
                            (left, right) -> left));
        } finally {
            if (widen) {
                if (previous == null) {
                    TenantScopeHolder.clear();
                } else {
                    TenantScopeHolder.start(previous);
                }
            }
        }
    }

    @Override
    public void updateAgentInstance(Long sessionId, Long instanceId) {
        if (sessionId == null || instanceId == null) {
            return;
        }
        AgentSession session = getById(sessionId);
        if (session == null) {
            return;
        }
        session.setAgentInstanceId(instanceId);
        updateById(session);
    }

    @Override
    public SessionVO findRouterSession(Long threadId, Long superAgentId) {
        if (threadId == null || superAgentId == null) {
            return null;
        }
        AgentSession session = lambdaQuery()
                .eq(AgentSession::getThreadId, threadId)
                .eq(AgentSession::getSuperAgentId, superAgentId)
                .eq(AgentSession::getSessionType, SessionType.ROUTER)
                .isNull(AgentSession::getParentSessionId)
                .eq(AgentSession::getStatus, SessionStatus.STATUS_ACTIVE)
                .orderByDesc(AgentSession::getId)
                .last("LIMIT 1")
                .one();
        return session == null ? null : sessionConverter.toVO(session);
    }

    @Override
    public void closeSession(Long id) {
        AgentSession session = getById(id);
        if (session == null) throw new BizException(InstanceErrorCode.SESSION_NOT_FOUND);
        session.setStatus(SessionStatus.STATUS_CLOSED);
        updateById(session);
    }

    @Override
    public void batchCloseSessions(List<Long> ids) {
        if (ids == null || ids.isEmpty()) return;
        lambdaUpdate()
                .in(AgentSession::getId, ids)
                .set(AgentSession::getStatus, SessionStatus.STATUS_CLOSED)
                .update();
    }

    @Override
    public void updateSummaryManually(Long sessionId, String summary) {
        AgentSession session = getById(sessionId);
        if (session == null) return;
        session.setSummary(summary);
        session.setSummaryUpdatedAt(java.time.LocalDateTime.now());
        updateById(session);
    }

    @Override
    public void touchSession(Long sessionId) {

        AgentSession session = getById(sessionId);
        if (session == null) return;
        // updateById triggers AuditMetaObjectHandler to set updatedAt = now
        session.setTitle(session.getTitle());
        updateById(session);
    }

    @Override
    public void bindWorkItem(Long sessionId, Long workItemId) {
        if (sessionId == null || workItemId == null) {
            return;
        }
        lambdaUpdate()
                .eq(AgentSession::getId, sessionId)
                .set(AgentSession::getWorkItemId, workItemId)
                .update();
    }

    @Override
    public void updateSummary(Long sessionId, String summary, String summaryUpdatedAt, Long modelRouteId) {
        AgentSession session = getById(sessionId);
        if (session == null) return;
        session.setSummary(summary);
        try {
            session.setSummaryUpdatedAt(java.time.LocalDateTime.parse(summaryUpdatedAt));
        } catch (Exception e) {
            session.setSummaryUpdatedAt(java.time.LocalDateTime.now());
        }
        session.setSummaryModelRouteId(modelRouteId);
        updateById(session);
    }

    @Override
    public void assertSurfaceAllowed(Long sessionId) {
        AgentSession session = getById(sessionId);
        if (session == null) {
            throw new BizException(InstanceErrorCode.SESSION_NOT_FOUND);
        }
        // Training sessions are deliberately created on a Worker instance that has
        // allowConsoleSession=false. The owner may drive the session from the console
        // training surface; other users still cannot open it.
        if (SessionType.TRAINING.equals(session.getSessionType())
                && SessionSurfaceHolder.current() == SessionSurface.CONSOLE
                && AuthContext.getUsername() != null
                && AuthContext.getUsername().equals(session.getCreatedBy())) {
            return;
        }
        AgentInstance instance = instanceMapper.selectById(session.getAgentInstanceId());
        if (instance == null) {
            throw new BizException(InstanceErrorCode.INSTANCE_NOT_FOUND);
        }
        assertSurfaceAllowed(instance);
    }

    /** Single implementation of the surface switch check; createSession reuses the already-loaded instance to avoid a second DB lookup. */
    private void assertSurfaceAllowed(AgentInstance instance) {
        SessionSurfacePolicy.assertAllowed(SessionSurfaceHolder.current(),
                instance.getAllowConsoleSession(), instance.getAllowWidgetSession());
    }
}
